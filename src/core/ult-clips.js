/* ---- キーフレームの検査用 --------------------------------------------
   「力の伝達」は言葉で書いても守られないので、機械的に測れる形にする。
   各フレームが構えからどれだけ離れているかを、身体の部位ごとに合計する。
   tests/unit/ult-clips.test.js がこれを使って、
     ・沈みのフレームでは脚が先に動いていること
     ・腕が伸び切るのは脚が動き出した後であること
     ・戻りでは腰が先に帰り、腕が遅れて残っていること
   を検査する。 */
function deltaArr(a, b){
  if(!a || !b) return 0;
  let s = 0;
  for(let i=0;i<Math.max(a.length, b.length);i++) s += Math.abs((a[i]||0) - (b[i]||0));
  return s;
}
function deltaNum(a, b){
  if(a == null || b == null) return 0;
  return Math.abs(a - b);
}

export function chainProfile(frames, stance){
  return frames.map(f=>({
    t: f.t,
    legs:   deltaNum(f.hipL, stance.hipL) + deltaNum(f.hipR, stance.hipR)
          + deltaNum(f.kneeL, stance.kneeL) + deltaNum(f.kneeR, stance.kneeR),
    waist:  deltaArr(f.waist, stance.waist),
    arms:   deltaArr(f.shL, stance.shL) + deltaArr(f.shR, stance.shR)
          + deltaNum(f.elL, stance.elL) + deltaNum(f.elR, stance.elR),
    /* 弓は照準が常にワールド基準(aimWorld)なので wep が動かない。
       弓にとっての「武器の動作」は引き絞り(draw)なので、そちらを足す。
       剣・斧・杖では draw が無いので何も変わらない */
    weapon: deltaArr(f.wep, stance.wep) + deltaNum(f.draw, stance.draw),
  }));
}

// 最大値を取るフレームの番号
export function peakIndex(profile, key){
  let best = 0, bestV = -Infinity;
  profile.forEach((p, i)=>{ if(p[key] > bestV){ bestV = p[key]; best = i; } });
  return best;
}

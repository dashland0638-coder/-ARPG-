/* 必殺技(メイン武器)のモーションと、その一撃が届く瞬間の定義。

   ■ なぜ core に置くのか
   通常攻撃・スキル・回避の型は 05-rendering-rig.js の CLIPS 表にある。
   必殺技の型だけをここへ出したのは、**キーフレームの組み立て方そのものを
   ユニットテストで縛りたい**ため。下に書く「力の伝達」は言葉で書いても
   守られない ―― 実際に足→腰→肩→武器の順に動き出しているか、戻りが
   その逆順になっているかを機械的に検査する(tests/unit/ult-clips.test.js)。

   STANCE や F() は 05 側の都合(職ごとの構え表)なので、この関数は
   「構えを返す関数」を受け取る形にしてある。呼び出し側で
   buildUltClips(S) とするだけで、既存の CLIPS へそのまま流し込める。

   ■ 力の伝達(振り)
   悪い例は「腕だけ動く / 武器だけ振る / 身体が置いていかれる」。
   そうならないよう、1本のクリップを必ず次の役割のフレームで構成する:

     0.00 構え    ―― わずかに引く(push 負)
     0.12 沈み    ―― 膝が曲がり腰が逆へ捻れる。腕はまだ構えのまま
     0.30 駆動    ―― 脚が地面を押し、腰が回る。肩がやっと追い始める
     0.45 接触    ―― 腰・肩・肘・武器が伸び切る。踏み込み(push)最大
     0.62 吸収    ―― 武器が振り抜けて行き過ぎ、膝が沈んで衝撃を受ける
     0.82 巻戻し  ―― 腰がほどけていく。腕はまだ後ろに残っている
     1.00 構えへ

   つまり出は 足 → 腰 → 胸郭(=waist と肩) → 腕 → 武器、
   戻りは 武器 → 腕 → 肩 → 腰 → 脚 の順になる。

   ■ このリグの制約(正直に書いておく)
   胸郭そのもののチャンネルは無い。ベルトから上はすべて waist ピボットに
   ぶら下がっているので、「胸郭のひねり」は waist の回転と肩の角度の差で
   表現している。脚も hip/knee の x 回転だけで、横への開きは作れない。

   ■ 符号(既存クリップから読み取った約束ごと)
     waist[0] +  前傾(うつむく)      waist[1] +  左へ捻る     waist[2] + 右へ傾ぐ
     shL/shR[0] + 腕を後ろ(振り上げ)  −  腕を前へ
     elL/elR    − 肘を曲げる
     hipL/hipR  + 脚を後ろへ           −  脚を前へ
     kneeL/kneeR + 膝を曲げる
     push 前進(m)  drop 沈む(m)  lift 浮く(m)
     wep [刃の向き3, 刃筋の向き3]
*/

function F(t, o){ const out = Object.assign({}, o); out.t = t; return out; }

/* 必殺技の一撃が届く瞬間(クリップ長に対する割合)。

   通常攻撃は core/swing-timing.js が「判定・SE・見た目」を1点へ揃えて
   いるが、必殺技はその対象外だった ―― fireUltimate() が入力の瞬間に
   ダメージも VFX も SE も全部出し、モーションだけが後から振られていた。
   大きな予備動作を持つ技ほどズレが目立つ(剣士の渾身の斬撃は、剣が
   当たりに行くより 0.3 秒早く敵が吹き飛んでいた)。

   ここの値は上の構成でいう「接触」フレームの t。入力レスポンス
   (ゲージ消費・モーション開始・画面フラッシュ)は従来どおり即座に走らせ、
   ダメージ・VFX・SE だけをこの瞬間まで遅らせる。 */

/* サブ武器の必殺技(WEAPON_ULT_BY_KEY、12-progression-ui.js)は通常攻撃の
   型を流用しているので、その型の「当たる瞬間」もここに持たせる。 */
export const ALT_ULT_IMPACT_FRAC = {
  ultSpear:      0.30,
  ultKatana:     0.26,
  ultSpellblade: 0.26,
};

export function ultImpactFrac(clip){
  const f = ULT_IMPACT_FRAC[clip];
  if(f != null) return f;
  const a = ALT_ULT_IMPACT_FRAC[clip];
  return a != null ? a : 0;
}

/* 遅らせてよい上限(秒)。

   予備動作が大きいほど「当たる瞬間」は後ろになるが、素直に掛け算すると
   魔導士や鷹の目で 0.45〜0.47 秒になり、押してから何も起きない時間が
   長すぎて「必殺技だけ極端に硬直する」状態になる。今の戦闘は短い攻撃
   間隔と細かい連撃を目指しているので、そちらを優先して頭を打つ。

   上限に当たった技は、見た目の接触フレームより少しだけ早く解決する
   ことになる ―― 完全な一致より手触りを取った、意図的な妥協。 */
export const ULT_MAX_IMPACT_DELAY = 0.30;

/* 実際に遅らせる秒数。クリップが無い/短い場合は 0(=従来どおり即時)。 */
export function ultImpactDelay(clip, swingDur){
  const frac = ultImpactFrac(clip);
  if(!(frac > 0) || !(swingDur > 0)) return 0;
  return Math.min(ULT_MAX_IMPACT_DELAY, frac * swingDur);
}

/* 必殺技が当たった瞬間の演出の強さ。

   通常ヒット(shake 0.06 / hitStop 0.016・上限 0.022)→ 必殺技 → 処刑
   (core/execution.js の EXECUTION_STYLE)という順に強くなる階層を作る。
   常に画面を派手にするのではなく、「今、大きな攻撃が発生した」と分かる
   瞬間だけ強くするのが狙い。tests/unit/execution.test.js がこの順序を
   機械的に検査している。 */
export const ULT_IMPACT_SHAKE = 0.16;
export const ULT_IMPACT_HITSTOP = 0.05;
export const ULT_IMPACT_HITSTOP_MAX = 0.055;

/* 見た目の接触フレームと、実際に当たる瞬間を一致させる時間伸縮。

   ULT_MAX_IMPACT_DELAY で頭を打った技は、そのままでは「クリップの接触
   フレーム(t=0.52)」と「ダメージが出る瞬間(実時間で t=0.34 相当)」が
   ずれてしまう ―― 上限を入れたせいで、直そうとしていたズレが戻ってくる。

   そこで再生の進み方そのものを折り曲げる。接触までを詰めて再生し、
   その先をゆっくり流す。溜めの「形」は保ったまま、刃が届く瞬間だけが
   ダメージの瞬間に重なる。

     warp(0) = 0 / warp(hitFrac) = contactFrac / warp(1) = 1、かつ単調増加

   通常攻撃の戦騎士に対して既に同じ考え方(core/swing-timing.js の
   warpSwingT)を使っているので、仕組みとしても新しくはない。 */
export function ultClipWarp(t, contactFrac, hitFrac){
  const x = t < 0 ? 0 : (t > 1 ? 1 : t);
  if(!(contactFrac > 0) || !(hitFrac > 0) || hitFrac >= 1 || contactFrac >= 1) return x;
  if(x <= hitFrac) return contactFrac * (x / hitFrac);
  return contactFrac + (1 - contactFrac) * ((x - hitFrac) / (1 - hitFrac));
}

